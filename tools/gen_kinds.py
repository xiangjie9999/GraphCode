"""Generate docs/KINDS.md from the capability registry that ships in the release.

    python tools/gen_kinds.py

Reads  Plugins/GraphCode/Resources/mcp-bridge/graphcode-capabilities.json
Writes docs/KINDS.md
Every number in that file comes from the registry; nothing is typed by hand.
"""
import collections
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
REGISTRY = os.path.join(ROOT, 'Plugins', 'GraphCode', 'Resources', 'mcp-bridge', 'graphcode-capabilities.json')
OUT = os.path.join(ROOT, 'docs', 'KINDS.md')

PRODUCT_NAMES = {
    'core': 'GraphCode Core', 'move': 'GraphCode Move', 'extension': 'GraphCode Core Extension',
    'world': 'GraphCode World', 'groom': 'GraphCode Groom', 'rig': 'GraphCode Rig',
    'play': 'GraphCode Play', 'shape': 'GraphCode Shape', 'integrate': 'GraphCode Integrate',
    'garment': 'GraphCode Garment',
}
KIND_NAMES = {
    'blueprint': 'Blueprint (Actor, Character, any class)', 'widget_blueprint': 'Widget Blueprint (UMG)',
    'animation_blueprint': 'Animation Blueprint', 'blueprint_interface': 'Blueprint Interface',
    'blueprint_function_library': 'Blueprint Function Library', 'blueprint_macro_library': 'Blueprint Macro Library',
    'user_struct': 'User-defined struct', 'user_enum': 'User-defined enum', 'material': 'Material',
    'material_instance': 'Material Instance', 'material_function': 'Material Function',
    'data_asset': 'Data Asset', 'level': 'Level (persistent level and its actors)', 'data_table': 'Data Table',
    'string_table': 'String Table', 'input_action': 'Enhanced Input Action',
    'input_mapping_context': 'Enhanced Input Mapping Context', 'curve_float': 'Float Curve',
    'curve_vector': 'Vector Curve', 'curve_linear_color': 'Linear Color Curve', 'curve_table': 'Curve Table',
    'skeletal_mesh': 'Skeletal Mesh', 'static_mesh': 'Static Mesh', 'texture_2d': 'Texture 2D',
    'sound_wave': 'Sound Wave', 'sound_cue': 'Sound Cue', 'external_actor': 'World Partition external actor',
    'font': 'Font', 'font_face': 'Font Face', 'foliage_type': 'Foliage Type',
    'physical_material': 'Physical Material', 'hlod_layer': 'HLOD Layer', 'render_target': 'Render Target',
    'data_registry': 'Data Registry', 'import': 'Import proposal (outside file)', 'skeleton': 'Skeleton',
    'physics_asset': 'Physics Asset', 'ik_rig': 'IK Rig', 'ik_retargeter': 'IK Retargeter',
    'anim_sequence': 'Animation Sequence', 'anim_montage': 'Animation Montage', 'blend_space': 'Blend Space',
    'level_sequence': 'Level Sequence (cinematics)', 'behavior_tree': 'Behavior Tree', 'state_tree': 'State Tree',
    'niagara_system': 'Niagara System', 'niagara_parameter_collection': 'Niagara Parameter Collection',
    'anim_composite': 'Animation Composite', 'niagara_sim_cache': 'Niagara Simulation Cache',
    'env_query': 'Environment Query (EQS)', 'metasound_source': 'MetaSound Source',
    'metasound_patch': 'MetaSound Patch', 'metahuman': 'MetaHuman', 'procedural_vegetation': 'Procedural Vegetation graph',
    'pcg_graph': 'PCG Graph', 'pcg_graph_instance': 'PCG Graph Instance', 'pcg_settings': 'PCG Settings',
    'groom': 'Groom', 'groom_binding': 'Groom Binding', 'control_rig': 'Control Rig',
}
ACCESS = {'writable': 'read + write', 'writable_if': 'write when available', 'read_only': 'read only'}


def main():
    with open(REGISTRY, encoding='utf-8') as fh:
        reg = json.load(fh)
    kinds = reg['kinds']
    by_product = collections.OrderedDict()
    for p in reg['products']:
        by_product[p['product']] = []
    for k in kinds:
        by_product.setdefault(k['product'], []).append(k)

    blocks = [b for k in kinds for b in k['blocks']]
    access = collections.Counter(b['access'] for b in blocks)
    creatable = sum(1 for k in kinds if k.get('create', {}).get('supported'))
    def omitted(k):  # the registry spells "omits nothing" as the single token `none`
        return [t for t in k.get('omits', []) if t != 'none']

    none_omitted = sum(1 for k in kinds if not omitted(k))
    tokens = {t for k in kinds for t in omitted(k)}

    out = []
    w = out.append
    w('# Asset kinds GraphCode reads and writes')
    w('')
    w('*Generated by `tools/gen_kinds.py` from `Plugins/GraphCode/Resources/mcp-bridge/graphcode-capabilities.json`,')
    w(f'the capability registry shipped in this release (registry version `{reg.get("version")}`). Do not edit by hand.*')
    w('')
    w('A **kind** is a type of Unreal asset that has one `.gc` text document. A **block** is one section of')
    w('that document (`properties`, `graph`, `components`...). `omits:` names what the document does **not**')
    w('carry, so a reviewer knows exactly where the text stops. Products marked *program-first* author')
    w('assets from their own recipe files (`.gcshape`, `.gcmove`, `.gcrig`, `.gcgroom`, `.gcgarment`, `.gchuman`,')
    w('`.gcw`) or drive the running game (`gc_play`), and their results appear here as the kinds they build.')
    w('')
    w('| | Count |')
    w('|---|---|')
    w(f'| Products in the registry | {len(reg["products"])} |')
    w(f'| Asset kinds | {len(kinds)} |')
    w(f'| Kinds a document can create from nothing | {creatable} |')
    w(f'| Blocks | {len(blocks)} ({access["writable"]} read + write, {access["writable_if"]} write when available, {access["read_only"]} read only) |')
    w(f'| Kinds that omit nothing (`omits: none`) | {none_omitted} |')
    w(f'| Distinct omission tokens | {len(tokens)} |')
    w('')
    for prod, ks in by_product.items():
        name = PRODUCT_NAMES.get(prod, prod)
        w(f'## {name}')
        w('')
        if not ks:
            w('*Program-first: no `.gc` kinds of its own. See the product section of the [README](../README.md#what-you-can-make).*')
            w('')
            continue
        w('| Kind | Create from text | Blocks | `omits:` |')
        w('|---|---|---|---|')
        for k in ks:
            label = KIND_NAMES.get(k['kind'], k['kind'])
            create = 'yes' if k.get('create', {}).get('supported') else 'existing assets'
            bl = ', '.join(f'`{b["name"]}`' + ('' if b['access'] == 'writable' else f' ({ACCESS.get(b["access"], b["access"])})')
                           for b in k['blocks'])
            om = ', '.join(f'`{t}`' for t in omitted(k)) or '`none`'
            w(f'| {label} `{k["kind"]}` | {create} | {bl} | {om} |')
        w('')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(out))
    print(f'wrote {OUT}: {len(kinds)} kinds, {len(blocks)} blocks, {creatable} creatable')


if __name__ == '__main__':
    main()
